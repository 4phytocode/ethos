export const ICON_NAMES = Object.keys(PATHS);

// icon('home') returns a new <svg>. Pass a size of 16, 24 or 48.
export function icon(name, size = 24) {
  const d = PATHS[name];
  if (!d) throw new Error('unknown icon: ' + name);
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  svg.classList.add('px-icon');
  const path = document.createElementNS(SVG_NS, 'path');
  path.setAttribute('d', d);
  path.setAttribute('fill', 'currentColor');
  svg.appendChild(path);
  return svg;
}

// Replaces the children of every [data-icon] element with that icon. Used for
// static markup in index.html, e.g. <span class="sb-glyph" data-icon="home">.
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    const size = Number(el.dataset.iconSize) || 24;
    el.replaceChildren(icon(el.dataset.icon, size));
  });
}
